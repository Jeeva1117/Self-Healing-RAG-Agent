"""Citation parsing, source provenance validation, and claim-to-evidence attribution."""

import re
from uuid import UUID

from app.schemas.chat import ChatCitation, ClaimCitation, SourceItem
from app.schemas.retrieval import RetrievalResultItem


class CitationValidationResult:
    """Encapsulates the audited citation mapping and validation metrics."""

    def __init__(
        self,
        sanitized_answer: str,
        sources: list[SourceItem],
        claim_citations: list[ClaimCitation],
        active_citations: list[ChatCitation],
        validation_passed: bool,
        used_source_count: int,
    ):
        self.sanitized_answer = sanitized_answer
        self.sources = sources
        self.claim_citations = claim_citations
        self.active_citations = active_citations
        self.validation_passed = validation_passed
        self.used_source_count = used_source_count


class CitationValidator:
    """Audits and validates citations generated by LLM against authentic database chunks."""

    _CITATION_PATTERN = re.compile(r"\[(\d+(?:\s*,\s*\d+)*)\]")

    @classmethod
    def validate_and_map(
        cls,
        raw_answer: str,
        retrieved_chunks: list[RetrievalResultItem],
        is_general_answer: bool = False,
    ) -> CitationValidationResult:
        """Validates all model-generated citations against provided retrieved chunks.

        1. Replaces or removes unknown / hallucinated citation IDs (e.g. [99]).
        2. Maps valid citation numbers to authentic database chunk and document IDs.
        3. Segments answer text into claims and associates each with supporting chunk IDs.
        4. Distinguishes retrieved chunks from sources actually utilized in the final answer.
        """
        if is_general_answer:
            return CitationValidationResult(
                sanitized_answer=raw_answer,
                sources=[],
                claim_citations=[],
                active_citations=[],
                validation_passed=True,
                used_source_count=0,
            )

        valid_range = set(range(1, len(retrieved_chunks) + 1))
        chunk_by_idx = dict(enumerate(retrieved_chunks, start=1))

        cited_indices: set[int] = set()
        has_invalid_citations = False

        def replace_citations(match: re.Match) -> str:
            nonlocal has_invalid_citations
            nums_str = match.group(1)
            parsed_nums = [int(n.strip()) for n in nums_str.split(",") if n.strip().isdigit()]

            valid_nums = []
            for n in parsed_nums:
                if n in valid_range:
                    valid_nums.append(n)
                    cited_indices.add(n)
                else:
                    has_invalid_citations = True

            if valid_nums:
                return "[" + ", ".join(str(n) for n in sorted(set(valid_nums))) + "]"
            return ""

        # Sanitize answer text by filtering invalid bracketed references
        sanitized_answer = cls._CITATION_PATTERN.sub(replace_citations, raw_answer)

        # Build SourceItem list for all retrieved candidates
        sources: list[SourceItem] = []
        for idx, item in enumerate(retrieved_chunks, start=1):
            is_cited = idx in cited_indices
            sources.append(
                SourceItem(
                    chunk_id=item.chunk_id,
                    document_id=item.document_id,
                    document_version_id=item.document_version_id,
                    document_name=item.document_name,
                    chunk_index=item.chunk_index,
                    page_number=item.page_number,
                    section_title=item.section_title or f"Chunk #{item.chunk_index}",
                    excerpt=item.content,
                    relevance_score=item.reranker_score if item.reranker_score is not None else item.vector_score,
                    is_cited=is_cited,
                )
            )

        # Build active ChatCitation list for cited chunks (or top retrieved if none explicitly bracketed)
        active_citations: list[ChatCitation] = []
        if cited_indices:
            for idx in sorted(cited_indices):
                item = chunk_by_idx[idx]
                active_citations.append(
                    ChatCitation(
                        id=idx,
                        chunk_id=item.chunk_id,
                        document_id=item.document_id,
                        title=item.document_name,
                        section=item.section_title or f"Chunk #{item.chunk_index}",
                        page=item.page_number,
                        snippet=item.content,
                        relevance_score=item.reranker_score if item.reranker_score is not None else item.vector_score,
                    )
                )
        else:
            # If no bracketed citations are found in answer (e.g. short summary),
            # provide retrieved chunks with transparent indexing
            for idx, item in enumerate(retrieved_chunks, start=1):
                active_citations.append(
                    ChatCitation(
                        id=idx,
                        chunk_id=item.chunk_id,
                        document_id=item.document_id,
                        title=item.document_name,
                        section=item.section_title or f"Chunk #{item.chunk_index}",
                        page=item.page_number,
                        snippet=item.content,
                        relevance_score=item.reranker_score if item.reranker_score is not None else item.vector_score,
                    )
                )

        # Extract Claim-to-Evidence mappings
        claim_citations: list[ClaimCitation] = []
        sentences = re.split(r"(?<=[.!?\n])\s+", sanitized_answer)
        claim_counter = 1

        for sentence in sentences:
            s_clean = sentence.strip()
            if not s_clean:
                continue

            matches = cls._CITATION_PATTERN.findall(s_clean)
            if matches:
                matched_chunk_ids: list[UUID] = []
                for match_str in matches:
                    nums = [int(n.strip()) for n in match_str.split(",") if n.strip().isdigit()]
                    for n in nums:
                        if n in chunk_by_idx:
                            matched_chunk_ids.append(chunk_by_idx[n].chunk_id)

                if matched_chunk_ids:
                    # Deduplicate chunk IDs preserving order
                    deduped_ids = list(dict.fromkeys(matched_chunk_ids))
                    clean_text = cls._CITATION_PATTERN.sub("", s_clean).strip()
                    claim_citations.append(
                        ClaimCitation(
                            claim_id=f"claim-{claim_counter}",
                            text=clean_text or s_clean,
                            source_chunk_ids=deduped_ids,
                        )
                    )
                    claim_counter += 1

        validation_passed = not has_invalid_citations and (len(cited_indices) > 0 or len(retrieved_chunks) == 0)

        return CitationValidationResult(
            sanitized_answer=sanitized_answer,
            sources=sources,
            claim_citations=claim_citations,
            active_citations=active_citations,
            validation_passed=validation_passed,
            used_source_count=len(cited_indices),
        )
